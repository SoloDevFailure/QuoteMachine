import {chromium} from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({headless:true,channel:"msedge"});
const context=await browser.newContext({viewport:{width:390,height:844}});
const page=await context.newPage(),errors=[];page.on("pageerror",e=>errors.push(String(e)));
await page.goto(process.env.PILLAR_PRODUCTION_URL || "http://127.0.0.1:4176/");
await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
await page.waitForFunction(()=>Boolean(navigator.serviceWorker.controller));
const cached=await page.evaluate(async()=>{const keys=await caches.keys();const cache=await caches.open(keys.find(k=>k.startsWith("fortestack-shell-")));return (await cache.keys()).map(r=>r.url);});
assert.ok(cached.some(url=>url.includes("generateWorkOrder")));assert.ok(cached.some(url=>url.includes("DejaVuSans")));
await page.getByRole("button",{name:"NEW JOB",exact:false}).click();
await page.getByLabel("Job name *",{exact:true}).fill("Offline inspection");
await page.getByLabel("Client name",{exact:true}).fill("Local client");
await page.getByRole("button",{name:"Create job & open notebook",exact:true}).click();
await page.getByRole("textbox",{name:"Section notes",exact:true}).fill("This notebook and its PDF were generated offline.");
await page.getByRole("button",{name:"Collapse section",exact:true}).click();
await context.setOffline(true);
await page.reload();
await page.getByRole("heading",{name:"Offline inspection",exact:true}).waitFor();
await page.getByRole("button",{name:"GENERATE WORK ORDER",exact:false}).click();
await page.getByRole("button",{name:"Generate A4 PDF",exact:true}).click();
await page.getByRole("link",{name:"Download PDF",exact:false}).waitFor({timeout:30000});
assert.deepEqual(errors,[]);
console.log("PASS: complete production shell cached, saved job reopens offline, first PDF generation works offline");
await browser.close();
